function calculateFormula(a, b, c) {
    a = parseFloat(a);
    b = parseFloat(b);
    c = parseFloat(c);

    // 1. Проверка: являются ли введённые данные числами
    if (isNaN(a) || isNaN(b) || isNaN(c)) {
        return "Ошибка: Введены некорректные данные (не числа).";
    }

    // 2. Проверка деления на ноль (для знаменателя 2a)
    if (a === 0) {
        return "Ошибка: параметр 'a' не может быть равен 0 (деление на ноль).";
    }

    // 3. Проверка для b^-2 (деление на ноль, если b=0)
    if (b === 0) {
        return "Ошибка: параметр 'b' не может быть равен 0 (вычисление b^-2).";
    }

    // 4. Проверка выражения под корнем (дискриминант)
    let discriminant = Math.pow(b, 2) + 4 * a * c;
    if (discriminant < 0) {
        return "Ошибка: под корнем отрицательное число (" + discriminant + ").";
    }

    // Если все проверки пройдены, выполняем расчет
    let term1 = (b + Math.sqrt(discriminant)) / (2 * a);
    let term2 = Math.pow(a, 3) * c;
    let term3 = Math.pow(b, -2);
    
    let result = term1 - term2 + term3;

    // 5. Проверка: не является ли сам результат бесконечностью или ошибкой
    if (!isFinite(result)) {
        return "Ошибка: Результат является бесконечным или неопределенным.";
    }

    return result.toFixed(4); // Возвращаем результат, округленный до 4 знаков
}